def unet_block(c_in, c_out):
    return nn.Sequential(nn.Conv2d(c_in, c_out, 3, padding=1), nn.BatchNorm2d(c_out), nn.ReLU(),
                         nn.Conv2d(c_out, c_out, 3, padding=1), nn.BatchNorm2d(c_out), nn.ReLU())


class UNet(nn.Module):
    """Three levels down, a bottleneck and three levels up with skip connections."""

    def __init__(self, c=8, n_classes=2):
        super().__init__()
        self.down1, self.down2, self.down3 = unet_block(1, c), unet_block(c, 2 * c), unet_block(2 * c, 4 * c)
        self.bottom = unet_block(4 * c, 8 * c)
        self.up3, self.dec3 = nn.ConvTranspose2d(8 * c, 4 * c, 2, stride=2), unet_block(8 * c, 4 * c)
        self.up2, self.dec2 = nn.ConvTranspose2d(4 * c, 2 * c, 2, stride=2), unet_block(4 * c, 2 * c)
        self.up1, self.dec1 = nn.ConvTranspose2d(2 * c, c, 2, stride=2), unet_block(2 * c, c)
        self.out = nn.Conv2d(c, n_classes, 1)

    def forward(self, x):
        d1 = self.down1(x)
        d2 = self.down2(F.max_pool2d(d1, 2))
        d3 = self.down3(F.max_pool2d(d2, 2))
        b = self.bottom(F.max_pool2d(d3, 2))
        u3 = self.dec3(torch.cat([self.up3(b), d3], dim=1))
        u2 = self.dec2(torch.cat([self.up2(u3), d2], dim=1))
        u1 = self.dec1(torch.cat([self.up1(u2), d1], dim=1))
        return self.out(u1)


def soft_dice_loss(logits, target):
    p = F.softmax(logits, dim=1)[:, 1]
    t = target.float()
    inter = (p * t).sum(dim=(1, 2))
    return 1 - ((2 * inter + 1) / (p.sum(dim=(1, 2)) + t.sum(dim=(1, 2)) + 1)).mean()


def dice(pred, true):
    """Dice coefficient of each frame: two boolean arrays of the same shape."""
    inter = (pred & true).sum(axis=(-2, -1))
    return 2 * inter / np.maximum(pred.sum(axis=(-2, -1)) + true.sum(axis=(-2, -1)), 1)


