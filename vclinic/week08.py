def fit_logistic(X, y, Cs=(0.01, 0.1, 1.0, 10.0), Xv=None, yv=None):
    """Standardise the columns and fit a logistic regression; with a validation set, keep the inverse regularisation strength with the largest validation AUC."""
    best = None
    for C in (Cs if Xv is not None else (1.0,)):
        model = make_pipeline(StandardScaler(), LogisticRegression(C=C, max_iter=5000)).fit(X, y)
        auc = roc_auc_score(yv, model.predict_proba(Xv)[:, 1]) if Xv is not None else 0.0
        if best is None or auc > best[1]:
            best = (model, auc)
    return best[0]


def logit(p):
    """The log-odds of a probability."""
    p = np.clip(p, 1e-6, 1 - 1e-6)
    return np.log(p / (1 - p))


def bootstrap_auc(y, p, n=2000, seed=2026):
    """AUC in n bootstrap samples of the patients: an array of n values."""
    rng = np.random.default_rng(seed)
    out = []
    while len(out) < n:
        i = rng.integers(0, len(y), len(y))
        if 0 < y[i].sum() < len(i):
            out.append(roc_auc_score(y[i], p[i]))
    return np.array(out)


def paired_bootstrap(y, p1, p2, n=2000, seed=2026):
    """The AUC of p1 minus the AUC of p2 in n bootstrap samples of the same patients: an array of n differences."""
    rng = np.random.default_rng(seed)
    out = []
    while len(out) < n:
        i = rng.integers(0, len(y), len(y))
        if 0 < y[i].sum() < len(i):
            out.append(roc_auc_score(y[i], p1[i]) - roc_auc_score(y[i], p2[i]))
    return np.array(out)


def calibration(y, p):
    """Calibration in the large (the intercept with the slope fixed at 1) and the calibration slope."""
    z = logit(p)
    a = 0.0
    for _ in range(50):
        q = 1 / (1 + np.exp(-(a + z)))
        a += (y - q).sum() / (q * (1 - q)).sum()
    slope = LogisticRegression(C=1e6, max_iter=5000).fit(z[:, None], y).coef_[0, 0]
    return a, slope


def reliability(y, p, bins=10):
    """Mean predicted risk and observed share of events in groups of equal size: two arrays."""
    order = np.argsort(p)
    groups = np.array_split(order, bins)
    return np.array([p[g].mean() for g in groups]), np.array([y[g].mean() for g in groups])


def laboratory(d):
    """Troponin in multiples of the upper reference limit of its assay: the log of the value at arrival and after one hour, the change in one hour, and whether the second value exists."""
    url = d["troponin_url"]
    t0, t1 = d["troponin_0h"] / url, d["troponin_1h"] / url
    return pd.DataFrame({"log_trop_0h": np.log(t0), "log_trop_1h": np.log(t1.fillna(t0)),
                         "delta_1h": (t1 - t0).fillna(0.0), "has_1h": t1.notna().astype(float)})


def echo(d):
    """The bedside echocardiogram: whether it was done, the ejection fraction (60 when not done) and a regional wall motion abnormality (0 when not done)."""
    return pd.DataFrame({"echo_done": d["echo_done"].astype(float), "lvef": d["lvef"].fillna(60.0), "rwma": d["rwma"].fillna(0.0)})


class ECGNet(nn.Module):
    """A one-dimensional convolutional network for a 12-lead ECG: four blocks, the mean of every channel over time and one output."""
    def __init__(self):
        super().__init__()
        block = lambda a, b: nn.Sequential(nn.Conv1d(a, b, 7, padding=3), nn.BatchNorm1d(b), nn.ReLU(), nn.MaxPool1d(2))
        self.features = nn.Sequential(block(12, 32), block(32, 64), block(64, 64), block(64, 64))
        self.head = nn.Linear(64, 1)

    def embed(self, x):
        return self.features(x).mean(dim=2)

    def forward(self, x):
        return self.head(self.embed(x)).squeeze(1)


def train_ecg(model, X, y, Xv, yv, epochs=12, seed=2026, verbose=True):
    """Adam with a learning rate of 0.001 in groups of 64 ECGs, each shifted in time by up to half a second; the weights of the epoch with the best validation AUC are kept."""
    torch.manual_seed(seed)
    X, y = torch.as_tensor(X), torch.as_tensor(y, dtype=torch.float32)
    optimiser = torch.optim.Adam(model.parameters(), lr=0.001)
    loss_fn = nn.BCEWithLogitsLoss()
    best, state = -1.0, None
    for epoch in range(epochs):
        model.train()
        order = torch.randperm(len(X))
        for i in range(0, len(X), 64):
            b = order[i:i + 64]
            xb = torch.roll(X[b], int(torch.randint(-50, 51, (1,))), dims=2)
            loss = loss_fn(model(xb), y[b])
            optimiser.zero_grad()
            loss.backward()
            optimiser.step()
        a = roc_auc_score(yv, ecg_predict(model, Xv))
        if a > best:
            best, state = a, copy.deepcopy(model.state_dict())
        if verbose:
            print(f"epoch {epoch + 1}: validation AUC {a:.3f}")
    model.load_state_dict(state)
    return best


def ecg_predict(model, X, batch=256):
    model.eval()
    return torch.cat([torch.sigmoid(model(torch.as_tensor(X[i:i + batch]))) for i in range(0, len(X), batch)]).numpy()


def ecg_embed(model, X, batch=256):
    model.eval()
    return torch.cat([model.embed(torch.as_tensor(X[i:i + batch])) for i in range(0, len(X), batch)]).numpy()


class Attention(nn.Module):
    """Self-attention with several heads; a mask removes the tokens of missing modalities."""
    def __init__(self, dim, heads):
        super().__init__()
        self.heads = heads
        self.qkv = nn.Linear(dim, 3 * dim)
        self.out = nn.Linear(dim, dim)
        self.weights = None

    def forward(self, x, keep):
        n, t, d = x.shape
        q, k, v = self.qkv(x).reshape(n, t, 3, self.heads, d // self.heads).permute(2, 0, 3, 1, 4)
        s = q @ k.transpose(-2, -1) / (d // self.heads) ** 0.5
        s = s.masked_fill(~keep[:, None, None, :], float("-inf"))
        a = torch.softmax(s, dim=-1)
        self.weights = a.detach()
        return self.out((a @ v).transpose(1, 2).reshape(n, t, d))


class Block(nn.Module):
    """A transformer block of Week 7, with the mask passed to its attention."""
    def __init__(self, dim, heads, hidden):
        super().__init__()
        self.norm1, self.attn = nn.LayerNorm(dim), Attention(dim, heads)
        self.norm2 = nn.LayerNorm(dim)
        self.mlp = nn.Sequential(nn.Linear(dim, hidden), nn.GELU(), nn.Linear(hidden, dim))

    def forward(self, x, keep):
        x = x + self.attn(self.norm1(x), keep)
        return x + self.mlp(self.norm2(x))


class HybridFusion(nn.Module):
    """Intermediate fusion: one small encoder for each modality, their outputs side by side, and a joint head."""
    def __init__(self, dims, dim=32):
        super().__init__()
        self.enc = nn.ModuleList([nn.Sequential(nn.Linear(d, dim), nn.ReLU()) for d in dims])
        self.head = nn.Sequential(nn.Linear(dim * len(dims), dim), nn.ReLU(), nn.Dropout(0.2), nn.Linear(dim, 1))

    def forward(self, xs, keep):
        h = [e(x) * k[:, None] for e, x, k in zip(self.enc, xs, keep.T)]
        return self.head(torch.cat(h, dim=1)).squeeze(1)


class AttentionFusion(nn.Module):
    """Attention-based fusion: one token for each modality and a class token pass through two transformer blocks; missing modalities are masked."""
    def __init__(self, dims, dim=32, depth=2, heads=4):
        super().__init__()
        self.enc = nn.ModuleList([nn.Linear(d, dim) for d in dims])
        self.kind = nn.Parameter(torch.randn(1, len(dims), dim) * 0.02)
        self.cls = nn.Parameter(torch.zeros(1, 1, dim))
        self.blocks = nn.ModuleList([Block(dim, heads, 2 * dim) for _ in range(depth)])
        self.norm, self.head = nn.LayerNorm(dim), nn.Linear(dim, 1)

    def forward(self, xs, keep):
        t = torch.stack([e(x) for e, x in zip(self.enc, xs)], dim=1) + self.kind
        t = torch.cat([self.cls.expand(len(t), -1, -1), t], dim=1)
        keep = torch.cat([torch.ones(len(t), 1, dtype=torch.bool), keep], dim=1)
        for block in self.blocks:
            t = block(t, keep)
        return self.head(self.norm(t[:, 0])).squeeze(1)


def train_fusion(model, xs, keep, y, xs_v, keep_v, yv, epochs=40, seed=2026, drop=0.0, verbose=False):
    """Adam in groups of 64 patients; with drop > 0 each present modality is hidden at random during training (modality dropout). The weights of the epoch with the best validation AUC are kept."""
    torch.manual_seed(seed)
    xs = [torch.as_tensor(x, dtype=torch.float32) for x in xs]
    keep, y = torch.as_tensor(keep, dtype=torch.bool), torch.as_tensor(y, dtype=torch.float32)
    optimiser = torch.optim.Adam(model.parameters(), lr=0.001, weight_decay=1e-4)
    loss_fn = nn.BCEWithLogitsLoss()
    best, state = -1.0, None
    for epoch in range(epochs):
        model.train()
        order = torch.randperm(len(y))
        for i in range(0, len(y), 64):
            b = order[i:i + 64]
            kb = keep[b]
            if drop > 0:
                kb = kb & (torch.rand(kb.shape) >= drop)
                kb[kb.sum(dim=1) == 0, 0] = True
            loss = loss_fn(model([x[b] for x in xs], kb), y[b])
            optimiser.zero_grad()
            loss.backward()
            optimiser.step()
        a = roc_auc_score(yv, fusion_predict(model, xs_v, keep_v))
        if a > best:
            best, state = a, copy.deepcopy(model.state_dict())
        if verbose:
            print(f"epoch {epoch + 1}: validation AUC {a:.3f}")
    model.load_state_dict(state)
    return best


def fusion_predict(model, xs, keep):
    model.eval()
    xs = [torch.as_tensor(x, dtype=torch.float32) for x in xs]
    return torch.sigmoid(model(xs, torch.as_tensor(keep, dtype=torch.bool))).numpy()


