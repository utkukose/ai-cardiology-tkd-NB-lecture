_KEYS = {'1.1': '7.1', '1.2': '7.2', '1.3': '7.3'}   # the name of an exercise in the Jupyter notebook and in the tables


def _table(language, key, variables):
    scope = dict(globals())
    scope.update(variables)
    exec(_TABLES[language], scope)
    make = scope["exercise_table" if language == "en" else "alistirma_tablosu"]
    return make(_KEYS.get(key, key))


def exercise_table(key, **variables):
    """The table "data" of the prompt of an exercise, built from the variables of the Jupyter notebook that it names."""
    return _table("en", key, variables)


def alistirma_tablosu(anahtar, **degiskenler):
    """Bir alıştırmanın promptundaki "veri" tablosu: Jupyter Notebook'ta adı verilen değişkenlerden hazırlanır."""
    return _table("tr", anahtar, degiskenler)
