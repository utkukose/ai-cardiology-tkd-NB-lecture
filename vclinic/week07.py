def to_patches(image, p):
    """Cut a grey image into squares of p x p pixels, row by row; each square becomes a row of p * p numbers."""
    h, w = image.shape[0] // p * p, image.shape[1] // p * p
    return image[:h, :w].reshape(h // p, p, w // p, p).transpose(0, 2, 1, 3).reshape(-1, p * p)


def rollout(maps):
    """Attention rollout: the attention of each layer, with the residual connection added, multiplied from the first layer to the last."""
    r = np.eye(maps.shape[-1])
    for a in maps:
        a = 0.5 * a + 0.5 * np.eye(len(a))
        r = (a / a.sum(axis=1, keepdims=True)) @ r
    return r


class Attention(nn.Module):
    """Self-attention with several heads; the weights of the last call are kept for the maps."""
    def __init__(self, dim, heads):
        super().__init__()
        self.heads = heads
        self.qkv = nn.Linear(dim, 3 * dim)
        self.out = nn.Linear(dim, dim)
        self.weights = None

    def forward(self, x):
        n, t, d = x.shape
        q, k, v = self.qkv(x).reshape(n, t, 3, self.heads, d // self.heads).permute(2, 0, 3, 1, 4)
        a = torch.softmax(q @ k.transpose(-2, -1) / (d // self.heads) ** 0.5, dim=-1)
        self.weights = a.detach()
        return self.out((a @ v).transpose(1, 2).reshape(n, t, d))


class Block(nn.Module):
    """A transformer block: attention and a small two-layer network, each after layer normalisation and with a residual connection."""
    def __init__(self, dim, heads, hidden):
        super().__init__()
        self.norm1, self.attn = nn.LayerNorm(dim), Attention(dim, heads)
        self.norm2 = nn.LayerNorm(dim)
        self.mlp = nn.Sequential(nn.Linear(dim, hidden), nn.GELU(), nn.Linear(hidden, dim))

    def forward(self, x):
        x = x + self.attn(self.norm1(x))
        return x + self.mlp(self.norm2(x))


class SmallViT(nn.Module):
    """A small vision transformer: squares of 8 x 8 pixels as tokens, a class token, learned positions and four blocks."""
    def __init__(self, size=64, patch=8, dim=64, depth=4, heads=4, channels=1, outputs=1):
        super().__init__()
        self.embed = nn.Conv2d(channels, dim, patch, stride=patch)    # one linear map for every square
        n = (size // patch) ** 2
        self.cls = nn.Parameter(torch.zeros(1, 1, dim))
        self.pos = nn.Parameter(torch.randn(1, n + 1, dim) * 0.02)
        self.blocks = nn.ModuleList([Block(dim, heads, 2 * dim) for _ in range(depth)])
        self.norm = nn.LayerNorm(dim)
        self.head = nn.Linear(dim, outputs)

    def encode(self, t):
        t = torch.cat([self.cls.expand(len(t), -1, -1), t], dim=1) + self.pos
        for block in self.blocks:
            t = block(t)
        out = self.head(self.norm(t)[:, 0])
        return out.squeeze(1) if out.shape[1] == 1 else out

    def forward(self, x):
        return self.encode(self.embed(x).flatten(2).transpose(1, 2))


def n_parameters(model):
    """The number of trainable weights of a network."""
    return sum(p.numel() for p in model.parameters() if p.requires_grad)


def bootstrap_auc(target, prob, groups, n=2000, seed=2026):
    """AUC in 2000 bootstrap samples that draw groups (patients or images) with replacement."""
    rng = np.random.default_rng(seed)
    names = np.unique(groups)
    rows = {g: np.where(groups == g)[0] for g in names}
    out = []
    for _ in range(n):
        idx = np.concatenate([rows[g] for g in rng.choice(names, len(names))])
        if 0 < target[idx].sum() < len(idx):
            out.append(roc_auc_score(target[idx], prob[idx]))
    return np.array(out)


def standardise(X):
    """Every patch on its own: mean grey value 0 and standard deviation 1."""
    X = np.asarray(X, dtype=np.float32)
    m, s = X.mean(axis=(1, 2), keepdims=True), X.std(axis=(1, 2), keepdims=True)
    return (X - m) / (s + 0.02)


def conv_block(a, b):
    """Convolution of 3 x 3, batch normalisation, ReLU and max pooling of 2 x 2: half the size, b channels."""
    return nn.Sequential(nn.Conv2d(a, b, 3, padding=1), nn.BatchNorm2d(b), nn.ReLU(), nn.MaxPool2d(2))


class SmallCNN(nn.Module):
    """Four convolution blocks (16, 32, 64 and 64 channels), the mean of every channel and one output."""
    def __init__(self):
        super().__init__()
        self.features = nn.Sequential(conv_block(1, 16), conv_block(16, 32), conv_block(32, 64), conv_block(64, 64))
        self.head = nn.Linear(64, 1)

    def forward(self, x):
        return self.head(self.features(x).mean(dim=(2, 3))).squeeze(1)


class Hybrid(SmallViT):
    """A hybrid: three convolution blocks turn the patch into 8 x 8 positions of 64 numbers, the tokens of two transformer blocks."""
    def __init__(self, dim=64, depth=2, heads=4):
        super().__init__(size=8, patch=1, dim=dim, depth=depth, heads=heads, channels=dim)
        self.embed = nn.Sequential(conv_block(1, 16), conv_block(16, 32), conv_block(32, dim))


@torch.no_grad()
def predict(model, X, batch=256):
    """The probability of a stenosis for every patch."""
    model.eval()
    X = torch.as_tensor(X, dtype=torch.float32)
    return torch.cat([torch.sigmoid(model(X[i:i + batch, None])) for i in range(0, len(X), batch)]).numpy()


def train(model, X, y, Xv, yv, epochs=8, seed=2026, verbose=True):
    """Adam with a learning rate of 0.001, groups of 64 patches turned by a random quarter turn and mirrored half of the time; the weights of the epoch with the best validation AUC are kept."""
    torch.manual_seed(seed)
    X, y = torch.as_tensor(X, dtype=torch.float32)[:, None], torch.as_tensor(y, dtype=torch.float32)
    optimiser = torch.optim.Adam(model.parameters(), lr=0.001)
    loss_fn = nn.BCEWithLogitsLoss()
    best, state = -1.0, None
    for epoch in range(epochs):
        model.train()
        order = torch.randperm(len(X))
        for i in range(0, len(X), 64):
            b = order[i:i + 64]
            xb = torch.rot90(X[b], int(torch.randint(0, 4, (1,))), dims=(2, 3))
            if torch.rand(1) < 0.5:
                xb = torch.flip(xb, dims=(3,))
            loss = loss_fn(model(xb), y[b])
            optimiser.zero_grad()
            loss.backward()
            optimiser.step()
        a = roc_auc_score(yv, predict(model, Xv))
        if a > best:
            best, state = a, copy.deepcopy(model.state_dict())
        if verbose:
            print(f"epoch {epoch + 1}: validation AUC {a:.3f}")
    model.load_state_dict(state)
    return best


