# The rules of ACDC on the measurements of the 90 patients
def acdc_rule(row):
    if row["lv_ef"] < 40 and row["lv_edvi"] > 100:
        return "DCM"
    if row["max_wall_mm"] > 15 and row["lv_ef"] >= 50:
        return "HCM"
    return "NOR"


class CmrCNN(nn.Module):
    """Three convolution blocks and a linear layer; input: two frames of a slice as two channels."""

    def __init__(self, n_classes=3, dropout=0.3, batchnorm=True, in_channels=2):
        super().__init__()
        layers, c_in = [], in_channels
        for c_out in (8, 16, 32):
            layers += [nn.Conv2d(c_in, c_out, 3, padding=1)]
            layers += [nn.BatchNorm2d(c_out)] if batchnorm else []
            layers += [nn.ReLU(), nn.MaxPool2d(2)]
            c_in = c_out
        self.features = nn.Sequential(*layers)
        self.classifier = nn.Sequential(nn.Flatten(), nn.Dropout(dropout), nn.Linear(32 * 8 * 8, n_classes))

    def forward(self, x):
        return self.classifier(self.features(x))


def train_model(model, X_tr, y_tr, X_va, y_va, epochs=40, lr=0.003, batch=16, seed=RANDOM_STATE, augment_fn=None):
    torch.manual_seed(seed)
    order_gen = torch.Generator().manual_seed(seed)
    optimizer = torch.optim.Adam(model.parameters(), lr=lr, weight_decay=1e-4)
    best, best_state, history = float("inf"), None, []
    for epoch in range(epochs):
        model.train()
        order = torch.randperm(len(y_tr), generator=order_gen)
        total = 0.0
        for start in range(0, len(y_tr), batch):
            j = order[start:start + batch]
            xb = X_tr[j] if augment_fn is None else augment_fn(X_tr[j], order_gen)
            loss = F.cross_entropy(model(xb), y_tr[j])
            optimizer.zero_grad()
            loss.backward()
            optimizer.step()
            total += loss.item() * len(j)
        model.eval()
        with torch.no_grad():
            val_loss = F.cross_entropy(model(X_va), y_va).item()
        history.append((total / len(y_tr), val_loss))
        if val_loss < best:
            best, best_state = val_loss, copy.deepcopy(model.state_dict())
    model.load_state_dict(best_state)
    return history


