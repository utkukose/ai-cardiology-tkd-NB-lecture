RANDOM_STATE = 2026   # the seed value of the course, as in the start cells


def bootstrap_auc(y, p_a, p_b, n_boot=2000, seed=RANDOM_STATE):
    """AUCs of two models and their difference in n_boot resamples of the test patients, drawn with replacement."""
    rng = np.random.default_rng(seed)
    y = np.asarray(y)
    rows = []
    for _ in range(n_boot):
        i = rng.integers(0, len(y), len(y))
        if y[i].min() == y[i].max():
            continue
        a, b = roc_auc_score(y[i], p_a[i]), roc_auc_score(y[i], p_b[i])
        rows.append({"a": a, "b": b, "difference": b - a})
    return pd.DataFrame(rows)


def interval(values, level=0.95):
    """The percentile interval of the bootstrap values."""
    return tuple(np.percentile(values, [50 * (1 - level), 100 - 50 * (1 - level)]))


def calibration(y, p, steps=50):
    """Calibration intercept (with the linear predictor as offset) and slope of predicted probabilities p, by Newton steps."""
    y = np.asarray(y, dtype=float)
    lp = np.log(p / (1 - p))
    a = 0.0
    for _ in range(steps):
        q = 1 / (1 + np.exp(-(a + lp)))
        a += (y - q).sum() / (q * (1 - q)).sum()
    Z = np.c_[np.ones_like(lp), lp]
    b = np.zeros(2)
    for _ in range(steps):
        q = 1 / (1 + np.exp(-Z @ b))
        b += np.linalg.solve(Z.T @ (Z * (q * (1 - q))[:, None]), Z.T @ (y - q))
    return float(a), float(b[1])


def slope_interval(y, p, n_boot=1000, seed=RANDOM_STATE):
    """The bootstrap percentile interval of the calibration slope."""
    rng = np.random.default_rng(seed)
    y, p = np.asarray(y), np.asarray(p)
    slopes = []
    for _ in range(n_boot):
        i = rng.integers(0, len(y), len(y))
        if y[i].min() < y[i].max():
            slopes.append(calibration(y[i], p[i])[1])
    return interval(slopes)


