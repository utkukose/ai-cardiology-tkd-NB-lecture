def shapley(values):
    """Exact Shapley values from the values of all coalitions: for each variable, the weighted mean of what it adds to the coalitions without it."""
    n = len(next(iter(values)))
    phi = np.zeros(n)
    for mask, value in values.items():
        size = sum(mask)
        for j in range(n):
            if mask[j] == 0:
                with_j = mask[:j] + (1,) + mask[j + 1:]
                weight = math.factorial(size) * math.factorial(n - size - 1) / math.factorial(n)
                phi[j] += weight * (values[with_j] - value)
    return phi


