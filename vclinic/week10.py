def sample_entropy(rr, m=1, r=0.03):
    """Sample entropy: minus the logarithm of the probability that two stretches of m + 1 intervals are alike, within r seconds, when their first m intervals are alike."""
    n = len(rr)

    def pairs(length):
        t = np.lib.stride_tricks.sliding_window_view(rr, length)[: n - m]
        alike = np.abs(t[:, None, :] - t[None, :, :]).max(axis=2) <= r
        return (alike.sum() - len(t)) / 2

    b, a = pairs(m), pairs(m + 1)
    return float(np.log(b / max(a, 1))) if b > 0 else float(np.log(n))


def features(rr):
    """The five numbers of a minute: heart rate, coefficient of variation, RMSSD divided by the mean RR, pNN50 and sample entropy."""
    d = np.diff(rr)
    return {"hr": 60 / rr.mean(), "cv": rr.std(ddof=1) / rr.mean(), "rmssd": np.sqrt(np.mean(d ** 2)) / rr.mean(),
            "pnn50": np.mean(np.abs(d) > 0.05), "sampen": sample_entropy(rr)}


def choose_threshold(p, y, sensitivity=0.95):
    """The highest threshold, in steps of 0.01, that still finds the given share of the AF minutes."""
    grid = np.round(np.arange(0.05, 0.96, 0.01), 2)
    return float(max(t for t in grid if (p[y == 1] >= t).mean() >= sensitivity))


def alarm_episodes(alarm):
    """Runs of consecutive alarm minutes, as (first, last) positions."""
    runs, first = [], None
    for k, a in enumerate(alarm):
        if a and first is None:
            first = k
        if not a and first is not None:
            runs.append((first, k - 1))
            first = None
    if first is not None:
        runs.append((first, len(alarm) - 1))
    return runs


def by_record(table, p, threshold):
    """For every record: the AF burden of the annotation and of the model, the alarm episodes and the false ones among them."""
    rows = []
    for record, part in table.assign(p=p).groupby("record", sort=True):
        alarm = (part["p"] >= threshold).to_numpy()
        runs = alarm_episodes(alarm)
        false = sum(1 for a, b in runs if part["af"].to_numpy()[a:b + 1].sum() == 0)
        rows.append({"record": record, "minutes": len(part), "burden": 100 * part["af_share"].mean(),
                     "model_burden": 100 * alarm.mean(), "episodes": len(runs), "false_episodes": false})
    return pd.DataFrame(rows).set_index("record")


def save_model(model, path):
    """Write the model as JSON and return the SHA-256 of the file, its fingerprint."""
    text = json.dumps(model, indent=2, sort_keys=True, ensure_ascii=False)
    pathlib.Path(path).write_text(text, encoding="utf-8")
    return hashlib.sha256(text.encode("utf-8")).hexdigest()


