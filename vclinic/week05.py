def youden_threshold(y_true, prob):
    """The threshold at which sensitivity + specificity is highest."""
    fpr, tpr, thresholds = roc_curve(y_true, prob)
    return float(thresholds[np.argmax(tpr - fpr)])


def se_sp_ppv(y_true, alarm):
    """Sensitivity, specificity and positive predictive value of a yes-or-no decision."""
    y_true, alarm = np.asarray(y_true, dtype=bool), np.asarray(alarm, dtype=bool)
    tp, fp = int((alarm & y_true).sum()), int((alarm & ~y_true).sum())
    return tp / y_true.sum(), 1 - fp / (~y_true).sum(), tp / max(1, tp + fp)


