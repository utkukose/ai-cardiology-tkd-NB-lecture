def tr_lower(text):
    """Lower case by the rules of Turkish: I becomes ı and İ becomes i, and the length of the text does not change."""
    return text.replace("I", "ı").replace("İ", "i").lower()


def words(text):
    """The words of a text in lower case: runs of letters and digits."""
    return re.findall(r"\w+", tr_lower(text))


def se_ppv_f1(y_true, y_pred):
    """Sensitivity, positive predictive value and F1 of a yes-or-no decision."""
    y_true, y_pred = np.asarray(y_true, dtype=bool), np.asarray(y_pred, dtype=bool)
    tp, fp, fn = int((y_pred & y_true).sum()), int((y_pred & ~y_true).sum()), int((~y_pred & y_true).sum())
    se = tp / max(1, tp + fn)
    ppv = tp / max(1, tp + fp)
    f1 = 2 * tp / max(1, 2 * tp + fp + fn)
    return se, ppv, f1


def next_other(mentions, i, text):
    """Where the next mention of another diagnosis starts; the end of the text when there is none."""
    return next((m[0] for m in mentions[i + 1:] if m[2] != mentions[i][2]), len(text))


def lab_value(text, name):
    """The first number after a laboratory name, for example egfr 54 or hba1c %7,8; None when it is missing."""
    m = re.search(name + r"\s*%?\s*(\d+(?:,\d+)?)", tr_lower(text))
    return float(m.group(1).replace(",", ".")) if m else None


def n_vessels(table):
    """Number of diseased vessels: territories LAD, LCX and RCA with a stenosis of 70 percent or more."""
    return sum(table[t] >= 70 for t in ("LAD", "LCX", "RCA"))


